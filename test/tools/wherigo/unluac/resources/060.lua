function spin()
  spinResult = math.random(4)
  if spinResult == 1 then
    zitemSpinner.Media = zmediaspinner1
  elseif spinResult == 2 then
    zitemSpinner.Media = zmediaspinner2
  elseif spinResult == 3 then
    zitemSpinner.Media = zmediaspinner3
  elseif spinResult == 4 then
    zitemSpinner.Media = zmediaspinner4
  end
  if currentSquare + spinResult > 25 then
    spinResultText = "You spun a " .. spinResult .. " which totals " .. currentSquare + spinResult .. "! You must land exactly on the Final Square! &nbsp;Stay here, your turn is over"
    Wherigo.MessageBox({
      Text = spinResultText,
      Media = zmediatooMuch,
      Callback = cartSlidesandLadders.MsgBoxCBFuncs.MsgBoxCB3
    })
  else
    zitemSpinner.Commands.Spin.Enabled = false
    disableCurrentZone(currentSquare)
    currentSquare = currentSquare + spinResult
    enableNextZone(currentSquare)
    spinResultText = "You spun a " .. spinResult .. "! Please move to Square " .. currentSquare .. "."
    Wherigo.MessageBox({
      Text = spinResultText,
      Media = zmediayouSpun,
      Callback = cartSlidesandLadders.MsgBoxCBFuncs.MsgBoxCB4
    })
  end
end
