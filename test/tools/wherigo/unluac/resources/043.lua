function AdjustDragonHealth(min, max)
  local result = math.random(min, max)
  if min == -1 then
    dragonHealth = 100
  else
    dragonHealth = dragonHealth - result
  end
  if dragonHealth > 0 then
    zcharacterDrachen.Name = woundedDragon[math.floor(dragonHealth / 10)]
    if zcharacterDrachen.Type == "PC" then
      zcharacterDrachen.Name = zcharacterDrachen.Name .. " (paralysiert)"
    end
  else
    zcharacterDrachen.Visible = false
    zitemDrachenaugenMedallion.Visible = true
  end
  return result
