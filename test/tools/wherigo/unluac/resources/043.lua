function AdjustHealth(min, max)
  local result = true
  if min == -1 then
    health = 100
  else
    health = health - math.random(min, max)
  end
  if health > 0 then
    ztaskGesundheit100.Name = "Gesundheit: " .. health .. "%"
  else
    ztaskGesundheit100.Name = "Du bist tot."
    ztimerpoison:Stop()
    result = false
    cleanup()
  end
  return result
end
